/**
 * Returns a consistent Daily Thought for the current day.
 * Deterministic hash based on the current date string (YYYY-MM-DD),
 * ensuring every user visiting on the same date sees the exact same thought.
 */
export function getDailyThought(date = new Date()) {
  const dateKey = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
  let hash = 0
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0
  }
  const index = hash % MOTIVATIONAL_THOUGHTS.length
  return {
    ...MOTIVATIONAL_THOUGHTS[index],
    dateKey,
  }
}

/**
 * Returns a random thought from the collection, avoiding the provided index if specified.
 */
export function getRandomThought(excludeId = null) {
  const eligible = excludeId
    ? MOTIVATIONAL_THOUGHTS.filter(t => t.id !== excludeId)
    : MOTIVATIONAL_THOUGHTS
  const index = Math.floor(Math.random() * eligible.length)
  return eligible[index]
}
